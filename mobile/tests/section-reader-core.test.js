const assert=require("node:assert/strict");
const {sectionsOf,navigation,moveIndex,chooseFitFont}=require("../src/section-reader-core");
const {parseSong}=require("../src/chords");
const rows=parseSong("[Coro]\nG    D\nTexto largo\n\n[Verso 1]\nAm\nTexto\n[Coro]\nG\nOtra letra");
rows.splice(3,0,{kind:"cue",action:"repeat",text:"Repetir"});
const sections=sectionsOf(rows);
assert.deepEqual(sections.map(x=>x.title),["Coro","Verso 1","Coro"]);
assert.deepEqual(sections.flatMap(x=>x.rows),rows);
assert.equal(sections[0].rows.find(x=>x.kind==="cue").action,"repeat");
assert.equal(sectionsOf(parseSong("Sin título"))[0].title,"Canto");
const seq=navigation([{rows},{rows}]);
assert.deepEqual(seq.map(x=>x.key),["0:0","0:1","0:2","1:0","1:1","1:2"]);
assert.equal(moveIndex(2,1,seq.length),3);
assert.equal(moveIndex(5,1,seq.length),5);
assert.equal(moveIndex(0,-1,seq.length),0);
assert.equal(chooseFitFont(10,46,n=>n<=19.35),19.3);
assert.equal(chooseFitFont(10,46,n=>n<=4),10);
assert.equal(chooseFitFont(10,46,()=>true),46);
const {scoreHtml}=require("../src/web-score-html");
const fitted=scoreHtml(rows,15,{mode:"auto",height:420});
assert.match(fitted,/fitHeight=420/);
assert.match(fitted,/rect.width<=target.clientWidth/);
assert.match(fitted,/rect.height\+2<=fitHeight/);
assert.match(fitted,/type:"score-fit"/);
assert.match(fitted,/fitMode="manual";zoom=next/);
console.log("Section navigation and measured fit preserve original rows and cues.");
