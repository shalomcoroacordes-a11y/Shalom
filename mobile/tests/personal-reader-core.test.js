const assert=require("node:assert/strict");
const {readingRows}=require("../src/personal-reader-core");
const {transposeOne}=require("../src/chords");
const {newEntry,newPart}=require("../src/personal-collections");
const song={id:"c1",title:"Canto de prueba",tone:"C",lyrics:"[Verso]\nC  G\nSeñor, escúchame\n\n[Coro]\nAm\nTe alabamos"};
const selected={...newPart(song.id),sectionIndex:1,sectionTitle:"Coro",shift:2,moment:"Comunión"};
const unavailable={...newPart("no-descargado"),shift:0};
const invalid={...newPart(song.id),sectionIndex:9,sectionTitle:"Estribillo",shift:0};
const entry={...newEntry("misa","Misa de prueba"),parts:[selected,unavailable,invalid]};
const original=JSON.stringify(entry);
const catalog=new Map([[song.id,song]]);
const rows=readingRows(entry,catalog,1);
assert.equal(rows.length,3);
assert.equal(rows[0].song,song);
assert.equal(rows[0].index,0);
assert.equal(rows[0].shift,3);
assert.equal(rows[0].tone,transposeOne("C",3));
assert.match(rows[0].resolved.lyrics,/Te alabamos/);
assert.doesNotMatch(rows[0].resolved.lyrics,/Señor, escúchame/);
assert.equal(rows[1].song,undefined,"No inventar cantos sin descargar");
assert.equal(rows[1].resolved.lyrics,null);
assert.match(rows[1].resolved.error,/biblioteca/);
assert.equal(rows[2].resolved.lyrics,null);
assert.match(rows[2].resolved.error,/estrofa/);
assert.deepEqual(readingRows(entry,catalog,0).map(r=>r.shift),[2,0,0],
 "Restituir los tonos originales sin mutar las composiciones");
assert.deepEqual(readingRows(null,catalog),[]);
assert.equal(JSON.stringify(entry),original,"No alterar las letras ni los datos personales");
console.log("SHALOM: lector local separa fragmentos, tonos y errores sin mutación.");
