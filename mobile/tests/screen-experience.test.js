// Regresión de experiencia de uso: jerarquía, rutas y ausencia de controles duplicados.
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {tabs,routeForTab,isSelectedTab}=require("../src/navigation-core");
const app=fs.readFileSync("App.js","utf8");
const profile=fs.readFileSync("src/profile-ui.js","utf8");
assert.deepEqual(tabs.map(t=>t[0]),["Inicio","Cantos","Repertorios","Mis creaciones","Perfil"]);
assert.equal(routeForTab("Mis creaciones"),"Mis colecciones");
assert.equal(routeForTab("Cantos"),"Canciones");
assert.equal(isSelectedTab("Mis colecciones","Mis creaciones"),true);
assert.match(app,/onPress:\(\)=>goTab\(routeForTab\(name\)\)/,"La barra abre creaciones locales");
assert.match(app,/function renderExplore\(\)/,"Existe exploración musical secundaria");
assert.match(app,/tab==="Explorar"\?renderExplore\(\)/);
const today=app.indexOf("h(View,{style:S.shalomToday},");
const search=app.indexOf("h(View,{style:S.homeSearchWrap},");
const banner=app.indexOf("h(Pressable,{style:S.spotifyBannerMini,");
assert.ok(today>=0&&search>today&&banner>search,"Hoy y búsqueda son prioritarios en Inicio");
assert.match(app,/Publicados por SHALOM/,"Distinguir repertorios oficiales");
assert.match(app,/tab!=="Artistas"&&tab!=="Explorar"/,"Explorar no muestra un botón de búsqueda que no funciona");
assert.match(app,/text:"Respaldo y restauración"/,"Respaldos accesibles en Configuración");
assert.doesNotMatch(app,/style:S.songActionBar/,"No duplicar la barra de controles de lectura");
assert.doesNotMatch(app,/!immersiveActive\?h\(AppSectionHeader/,"No dibujar doble cabecera");
assert.match(profile,/style:S.simpleIdentity/,"Profile matches the compact proposal");
assert.match(profile,/avatar\(profile,64\)/,"The normal profile shows an editable avatar");
assert.match(profile,/profileHeader\(draft,true\)/,"The editable cover remains accessible");
assert.doesNotMatch(profile,/profileHeader\(profile\)/,"Normal profile is not the oversized cover");
assert.match(profile,/Tus canciones favoritas/,"Favorites stay visible");
assert.match(profile,/Acerca de y donaciones/,"Existing information links are easy to find");
assert.match(profile,/Editar perfil/);
assert.match(profile,/Mis me gusta/);
assert.match(app,/label\("Bienvenido a SHALOM",S.spotifyWelcomeTitle\)/);
assert.match(app,/label\("Hoy en SHALOM",S.shalomTodayHeading\)/);
assert.match(app,/label\("Continuar donde te quedaste",S.spotifyHeading\)/);
assert.match(profile,/Configuración/);
assert.match(profile,/Respaldo y restauración/);
assert.match(profile,/Solicitar canto/);
assert.match(app,/onSettings:\(\)=>setSettingsOpen\(true\)/);
assert.match(app,/onBackup:\(\)=>goTab\("Respaldo"\)/);
assert.match(app,/onRequest:\(\)=>requestForm\("song"\)/);
assert.match(app,/renderToneStepper\(toned,true\)/);
assert.match(app,/label\("CAPO",S.songControlCaption\)/);
assert.match(app,/label\("LETRA",S.songControlCaption\)/);
assert.match(app,/onOpenLink:url=>openWeb\(url\)/);
assert.match(app,/h\(View,\{style:S.cantosFilterRow\}/,"Cantos uses screenshot-style filter chips");
assert.match(app,/label\("Biblioteca de cantos",S.cantosLibraryTitle\)/);
assert.match(app,/label\("Explorar también por",S.cantosExploreHeading\)/);
assert.match(app,/style:S.nav\}/,"One bottom navigation surface on all main tabs");
assert.match(app,/numberOfLines:2,[\s\S]*?minimumFontScale:\.78/,"Navigation labels wrap when necessary");
assert.match(app,/onOpenSongPage:\(\)=>openWeb\(songPermalink\(actionSong\)\)/);
assert.match(app,/onVideo:\(\)=>openSongVideo\(actionSong\)/);
console.log("SHALOM: jerarquía de pantallas y lectura simplificada verificadas.");
