const assert=require("node:assert/strict");
const fs=require("node:fs");
const {startStudioQueue,advanceStudioQueue}=require("../src/studio-queue");
const first=Object.freeze({song:{id:"s1"}}),second=Object.freeze({song:{id:"s2"}});
const entries=Object.freeze([{payload:first},{payload:second}]),plan={ready:entries};
assert.equal(startStudioQueue({}),null);
assert.equal(startStudioQueue(plan,2),null);
assert.equal(startStudioQueue(plan,-1),null);
const initial=startStudioQueue(plan);
assert.deepEqual(initial,{queue:{entries,index:0},payload:first});
assert.equal(initial.queue.entries,entries);
assert.equal(advanceStudioQueue(initial.queue,-1),null);
const next=advanceStudioQueue(Object.freeze(initial.queue),1);
assert.deepEqual(next,{queue:{entries,index:1},payload:second});
assert.equal(initial.queue.index,0);
assert.equal(advanceStudioQueue(next.queue,1),null);
assert.deepEqual(advanceStudioQueue(next.queue,-1),initial);
assert.equal(advanceStudioQueue(null,1),null);
assert.deepEqual(startStudioQueue(plan,1),next);
const app=fs.readFileSync("App.js","utf8");
assert.match(app,/startStudioQueue\(plan,index\)/);
assert.match(app,/advanceStudioQueue\(studioQueue,delta\)/);
console.log("SHALOM: local practice queue boundaries and immutability verified.");
