const assert=require("node:assert/strict");
const fs=require("node:fs");
const {newCollection,newEntry,newPart}=require("../src/personal-collections");
const {defaults}=require("../src/profile-core");
const {FORMAT,MAX_JSON_BYTES,buildBackup,readBackup,remapPhotos,summaryOf,referencedImages}=require("../src/personal-backup-core");
assert.equal(MAX_JSON_BYTES,64*1024*1024,"El límite de importación de respaldos grandes se comparte con la exportación");
const jpg=Buffer.from([255,216,255,224,0,16,74,70,73,70,0,1,2,3,4,5,255,217]).toString("base64");
const photo1="cover-photo-original.jpg",photo2="cover-profile-original.jpg";
const profile={...defaults(),name:"Jai",avatar:photo2,cover:photo2,banner:photo1};
const a=newCollection("Cantos para misa","#27c98b");
a.coverPhoto=photo1;
const misa=newEntry("misa","Domingo");
misa.parts.push({...newPart("song-1"),sectionIndex:1,sectionTitle:"Coro",shift:2,moment:"Comunión"});
const pop=newEntry("popurri","Alabanza");
pop.parts.push(newPart("song-2"));
const rep=newEntry("repertorio","Ensayo");
rep.parts.push(newPart("song-1"));
a.entries.push(misa,pop,rep);
const personal={version:1,collections:[a]};
const source={profile,personal,likedIds:["song-2","song-1"],lastRead:{type:"song",id:"song-1"}};
assert.deepEqual(referencedImages(profile,personal),[photo1,photo2]);
const serialized=buildBackup(source,[{name:photo1,base64:jpg},{name:photo2,base64:jpg}],"2026-11-19T12:00:00.000Z");
assert.ok(serialized.includes(FORMAT));
assert.ok(!serialized.includes("SHALOM1-"),"Backup is not a medley exchange code");
const parsed=readBackup(serialized);
assert.equal(parsed.profile.name,"Jai");
assert.equal(parsed.images.length,2);
assert.deepEqual(parsed.likedIds,["song-2","song-1"]);
assert.deepEqual(parsed.lastRead,{type:"song",id:"song-1"});
assert.deepEqual(summaryOf(parsed),{favorites:2,collections:1,misas:1,popurris:1,repertorios:1,images:2});
const newPhotos={};
newPhotos[photo1]="cover-imported1.jpg";newPhotos[photo2]="cover-imported2.jpg";
const newData=remapPhotos(parsed,newPhotos);
assert.equal(newData.profile.avatar,"cover-imported2.jpg");
assert.equal(newData.profile.cover,"cover-imported2.jpg");
assert.equal(newData.profile.banner,"cover-imported1.jpg");
assert.equal(newData.personal.collections[0].coverPhoto,"cover-imported1.jpg");
assert.equal(newData.personal.collections[0].entries[0].parts[0].sectionTitle,"Coro");
assert.equal(newData.personal.collections[0].entries[0].parts[0].shift,2);
assert.equal(newData.personal.collections[0].entries[0].parts[0].moment,"Comunión");
const altered=JSON.parse(serialized);altered.likedIds.push("song-3");
assert.throws(()=>readBackup(JSON.stringify(altered)),/incompleto|modificado/);
assert.throws(()=>readBackup("{no-json"),/no es un respaldo|vacío/);
assert.throws(()=>readBackup(serialized+"Z"),/no es un respaldo/);
assert.throws(()=>buildBackup(source,[]),/fotografías|portadas/);
assert.throws(()=>buildBackup(source,[{name:"../bad.jpg",base64:jpg},{name:photo2,base64:jpg}]),/fotografía|duplicadas|desconocidas/);
assert.throws(()=>buildBackup(source,[{name:photo1,base64:jpg},{name:photo1,base64:jpg}]),/duplicadas/);
const damaged=JSON.parse(serialized);
damaged.images[0].base64="AAAA";
assert.throws(()=>readBackup(JSON.stringify(damaged)),/incompleto|modificado/);
const empty=buildBackup({profile:defaults(),personal:{version:1,collections:[]},likedIds:[],lastRead:null},[]);
assert.deepEqual(summaryOf(readBackup(empty)),{favorites:0,collections:0,misas:0,popurris:0,repertorios:0,images:0});
const app=fs.readFileSync("App.js","utf8");
const ui=fs.readFileSync("src/personal-backup-ui.js","utf8");
const io=fs.readFileSync("src/personal-backup-io.js","utf8");
const notice=fs.readFileSync("src/local-notice.js","utf8");
const actions=fs.readFileSync("src/song-actions-ui.js","utf8");
assert.match(app,/tab==="Respaldo"\?h\(PersonalBackupScreen/,"Backup is accessible from the existing navigation");
const profileMenu=fs.readFileSync("src/profile-options-menu.js","utf8");
assert.match(profileMenu,/Respaldo y restauración/,"Backup appears in the native profile options");
assert.match(profileMenu,/onRequestClose:onDismiss/,"Android Back closes the menu without leaving the profile");
assert.match(app,/savePersonal\(prev,\{quiet:true\}\)/,"Undo restores previous collection state");
assert.match(app,/saveProfile\(prev,\{quiet:true\}\)/,"Undo restores previous profile state");
assert.match(app,/setFavoritesLocal\(prev\)/,"Undo restores the previous favorites");
assert.match(app,/showLocalNotice/,"Use unobtrusive notice instead of modal saved alert");
assert.match(notice,/Deshacer/,"Visible action for reversing the latest change");
assert.match(actions,/if\(outcome\?\.already\)Alert/,"Still report harmless duplicates");
assert.doesNotMatch(actions,/Guardado en este teléfono/,"Adding songs does not open a large success alert");
assert.match(ui,/¿Reemplazar tus datos personales\?/,"Import always requires explicit approval");
assert.match(ui,/El archivo no está cifrado/,"Explain backup privacy to users");
assert.match(io,/Sharing\.shareAsync/,"Native file share flow");
assert.match(io,/DocumentPicker\.getDocumentAsync/,"Native document import flow");
assert.match(io,/asset\.size>MAX_JSON_BYTES/,"El selector no acepta archivos superiores al límite en bytes");
assert.match(io,/file\.size>MAX_JSON_BYTES/,"La importación y la exportación deben comprobar el tamaño real en bytes");
assert.doesNotMatch(io,/límite permitido de 42 MB/,"No mostrar el antiguo límite incompatible con respaldos grandes");
assert.match(io,/file\.base64\(\)/,"Photo binary data is included, not just paths");
assert.match(io,/await dest\.write\(image\.base64,\{encoding:"base64"\}\)/,"Photos restored from encoded binary");
