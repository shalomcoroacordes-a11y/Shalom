const assert=require("node:assert/strict");
const D=require("../src/design-system");
const fs=require("node:fs");
assert.equal(D.GUTTER,16);assert.equal(D.ICON,24);assert.equal(D.TOUCH,48);
assert.deepEqual(D.normalizeStyles({title:{fontWeight:"850"},music:{fontFamily:"monospace",fontWeight:"750"}}),{title:{fontWeight:"500",fontFamily:"Inter"},music:{fontFamily:"monospace",fontWeight:"750"}});
const styles=fs.readFileSync("src/app-styles.js","utf8");
assert.match(styles,/page:\{paddingHorizontal:GUTTER/);
assert.match(styles,/navSelected:\{backgroundColor:"transparent"/);
assert.match(styles,/nav:\{backgroundColor:C.bg,borderTopWidth:1/);
assert.match(styles,/homeNavIcon:\{height:ICON,width:ICON/);
console.log("Shared spacing, typography and flat navigation verified.");
assert.equal(D.type.hero,24);assert.equal(D.type.secondary,14);
assert.deepEqual(D.normalizeStyles({header:{fontSize:24,fontWeight:"900"},body:{fontSize:16},layout:{flex:1}}),{header:{fontSize:24,fontWeight:"600",fontFamily:"Inter"},body:{fontSize:16,fontFamily:"Inter"},layout:{flex:1}});
const config=JSON.parse(fs.readFileSync("app.json","utf8")).expo.plugins.find(p=>Array.isArray(p)&&p[0]==="expo-font")[1];
assert.deepEqual(config.android.fonts[0].fontDefinitions.map(d=>d.weight),[400,500,600,700]);
for(const d of config.android.fonts[0].fontDefinitions)assert.ok(fs.statSync(d.path).size>100000);
