const assert=require("node:assert/strict");
const c=require("../src/liturgical-calendar");
assert.equal(c.advent(2026),"2026-11-29");assert.equal(c.advent(2027),"2027-11-28");
assert.equal(c.easter(2026),"2026-04-05");assert.equal(c.easter(2027),"2027-03-28");
assert.equal(c.baptism(2027),"2027-01-10");
assert.equal(c.liturgicalDay("2026-11-29").title,"I Domingo de Adviento");
assert.equal(c.liturgicalDay("2026-11-29").cycle,"B");
assert.equal(c.liturgicalDay("2027-02-10").title,"Miércoles de Ceniza");
assert.equal(c.liturgicalDay("2027-02-14").title,"I Domingo de Cuaresma");
assert.equal(c.liturgicalDay("2027-03-25").season,"triduum");
assert.equal(c.liturgicalDay("2027-05-16").title,"Pentecostés");
assert.equal(c.liturgicalDay("2027-05-17").season,"ordinary");
assert.equal(c.parseDay("2026-02-30"),null);
assert.equal(c.monthDays("2026-11")[6],"2026-11-01");
assert.equal(c.monthDays("2026-11").filter(Boolean).length,30);
assert.equal(c.shiftMonth("2026-12",1),"2027-01");
const event=(id,date,kind,published=true)=>({id,event_date:date,kind,is_published:published,items:[{song_id:"s"}]});
const model={repertoires:[event("draft","2026-11-29","misa",false),event("ensayo","2026-11-29","ensayo"),event("misa","2026-11-29","misa"),event("futuro","2026-12-01","misa")]};
const context=c.homeContext(model,new Date(2026,10,29,10));
assert.equal(context.events.length,3);assert.equal(context.current.id,"misa");assert.equal(context.greeting,"¡Feliz domingo!");
assert.equal(c.homeContext(model,new Date(2026,10,28,20)).next.id,"ensayo");
assert.equal(c.homeContext({},new Date(2026,10,28,20)).greeting,"Buenas noches");
console.log("Liturgical calendar: civil dates, verified major seasons, published choir events and contextual greeting verified.");
