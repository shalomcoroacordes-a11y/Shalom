"use strict";
const assert=require("node:assert/strict");
const C=require("../src/studio-collections");
const s={id:"a",title:"Ejemplo",lyrics:"C\nEjercicio",updated_at:"r1",_studio:{v:1,n:8}};
const parts=[{song_id:"a",studio_gap_ms:500},{song_id:"a",shift:2}];
assert.equal(C.sequencePlan([{song_id:"a"},{song_id:"a"}],[s],"Prueba"),null);
assert.equal(C.sequencePlan([parts[0],{song_id:"missing"}],[s],"Prueba"),null);
assert.equal(C.sequencePlan([{...parts[0],studio_gap_ms:-1},parts[1]],[s],"Prueba"),null);
const sequence=C.sequencePlan(parts,[s],"Prueba");
assert.equal(sequence.sequence.length,2);
assert.equal(sequence.sequence[0].gapMs,500);
assert.equal(sequence.sequence[1].shift,2);
const tracks=[{timeline:Array.from({length:8},()=>({duration:.25})),range:{start:2,end:6},gapMs:500},{timeline:Array.from({length:4},()=>({duration:.5})),gapMs:0}];
const schedule=C.scheduleTracks(tracks);
assert.equal(schedule.windows[0].start,0);assert.equal(schedule.windows[0].end,1);assert.equal(schedule.windows[1].start,1.5);
assert.equal(schedule.duration,3.5);
assert.deepEqual(schedule.events[0],{time:0,track:0,step:2});
assert.deepEqual(schedule.events[4],{time:1,track:0,release:true});
assert.deepEqual(schedule.events[5],{time:1.5,track:1,step:0});
assert.equal(C.scheduleTracks(tracks,2).duration,2);
assert.throws(()=>C.scheduleTracks([{...tracks[0],range:{start:2,end:10}},tracks[1]]),/Límites/);
console.log("SHALOM Studio: continuidad, pausas explícitas, compases con distintos tempos y límites verificados.");
