const assert=require("node:assert/strict");
const fs=require("node:fs");
const {emptyStore,newCollection,newPart,parseStore,exportCode}=require("../src/personal-collections");
const {items,createPersonal,receivePersonal,codePreview,kindName}=require("../src/personal-workflows");
const initial=emptyStore();
const created=createPersonal(initial,"misa","Misa del domingo");
assert.equal(initial.collections.length,0,"No debe mutar las colecciones originales");
assert.equal(created.folder.name,"Mis creaciones","Debe crear carpeta automática sin pedirla al usuario");
assert.equal(created.entry.title,"Misa del domingo");
assert.equal(created.entry.kind,"misa");
assert.equal(created.store.collections.length,1);
const another=createPersonal(created.store,"popurri","Alabanzas",null);
assert.equal(another.store.collections.length,1,"Reutiliza la carpeta automática");
assert.equal(items(another.store).length,2);
assert.equal(items(another.store,"misa").length,1);
assert.equal(items(another.store,"popurri").length,1);
const custom=newCollection("Ensayos","#2e84d7","guitar");
custom.coverPhoto="cover-propia1.jpg";
const withCustom={...another.store,collections:[...another.store.collections,custom]};
const repertoire=createPersonal(withCustom,"repertorio","Ensayo Shalom",custom.id);
assert.equal(repertoire.folder.id,custom.id);
assert.equal(repertoire.folder.coverPhoto,"cover-propia1.jpg");
assert.equal(repertoire.store.collections[0].entries.length,2,"No alterar carpetas antiguas");
assert.equal(repertoire.store.collections[1].entries.length,1);
assert.equal(items(repertoire.store,"repertorio").length,1);
assert.throws(()=>createPersonal(initial,"x","Nombre"),/Selecciona/);
assert.throws(()=>createPersonal(initial,"misa","  "),/nombre/);
assert.throws(()=>createPersonal(initial,"misa","Prueba","inexistente"),/carpeta/);
assert.equal(kindName("popurri"),"popurrí");
const shareable={...another.entry,parts:[newPart("canto-1"),newPart("canto-2")]};
const message="SHALOM: te comparto un popurrí\n"+exportCode(shareable);
const preview=codePreview(message,[{id:"canto-1"}]);
assert.equal(preview.count,2);
assert.equal(preview.missingCount,1,"Avisar al importar cantos que faltan");
assert.equal(preview.entry.kind,"popurri");
assert.equal(preview.entry.title,"Alabanzas");
const imported=receivePersonal(repertoire.store,message);
assert.equal(imported.folder.name,"Recibidos");
assert.equal(imported.entry.parts.length,2);
assert.equal(imported.store.collections.length,3);
const repeated=receivePersonal(imported.store,message);
assert.equal(repeated.store.collections.length,3,"Reutilizar carpeta Recibidos");
assert.equal(repeated.store.collections[2].entries.length,2);
assert.throws(()=>codePreview("texto cualquiera",[]),/código/);
const restored=parseStore(JSON.stringify(repeated.store));
assert.equal(items(restored).length,5);
assert.equal(restored.collections[1].coverPhoto,"cover-propia1.jpg","No perder portadas de colecciones anteriores");
const app=fs.readFileSync("App.js","utf8");
const profile=fs.readFileSync("src/profile-ui.js","utf8");
const screen=fs.readFileSync("src/personal-ui.js","utf8");
assert.match(profile,/Crear misa/);
assert.match(profile,/Crear repertorio/);
assert.match(profile,/Crear popurrí/);
assert.match(profile,/Recibir composición/);
assert.match(profile,/onOpenPersonal/,"Acceso directo a una composición existente");
assert.match(app,/personalAction:action\|\|null/,"Perfil envía acción de creación o recepción directamente");
assert.match(app,/personalNav:\{view:parts\?"reading":"editing"/,"Perfil abre composiciones sin entrar por carpetas");
assert.match(screen,/function homeView/,"Biblioteca personal como lista, no vista obligatoria de carpetas");
assert.match(screen,/function createView/);
assert.match(screen,/function receiveView/);
assert.match(screen,/function shareView/);
assert.match(screen,/Clipboard\.getStringAsync\(\)/,"Permitir pegar mensaje recibido");
assert.match(screen,/Clipboard\.setStringAsync\(shareMessage\)/,"Permitir copiar mensaje listo para compartir");
assert.match(screen,/function editView/);
assert.match(screen,/setExpandedPartId\(expanded\?null:p\.id\)/,"Opciones avanzadas ocultas hasta que se piden");
assert.match(screen,/if\(view==="share"\)/,"Botón Android vuelve desde compartir");
assert.match(screen,/if\(view==="import"\)/,"Botón Android vuelve desde importar");
assert.match(screen,/if\(view==="create"\)/,"Botón Android vuelve desde crear");
assert.match(screen,/if\(view==="folders"\)/,"Volver de carpeta avanzada al inicio de creaciones");
assert.doesNotMatch(fs.readFileSync("src/personal-workflows.js","utf8"),/fetch\s*\(|createClient|supabase\.(from|rpc)|https?:\/\//i,
 "El flujo nuevo no escribe en la nube");
console.log("SHALOM: crear, editar, compartir y recibir localmente sin carpetas obligatorias verificado.");
