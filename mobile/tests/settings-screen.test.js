const assert=require("node:assert/strict");
const fs=require("node:fs");
const src=fs.readFileSync("src/settings-screen-ui.js","utf8");
const h=(type,props,...children)=>({type,props:props||{},children});
const moduleMock={exports:{}};
new Function("require","module",src)(name=>name==="react"?{createElement:h}:{View:"View",Switch:"Switch",ActivityIndicator:"ActivityIndicator"},moduleMock);
const Screen=moduleMock.exports;
const events=[];
const props={S:{},C:{border:"border",green:"green",pale:"pale"},title:(...x)=>h("Title",null,...x),label:(...x)=>h("Label",null,...x),Card:"Card",Btn:"Btn",copy:null,model:{songs:[1,2],artists:[1],categories:[1,2,3]},wifiOnly:true,changeWifi:v=>events.push(["wifi",v]),busy:false,manualSync:()=>events.push(["sync"]),progress:"",error:"",goTab:v=>events.push(["tab",v]),openWeb:v=>events.push(["web",v])};
const flatten=node=>node&&typeof node==="object"?[node,...node.children.flatMap(flatten)]:[];
const all=flatten(Screen(props));
const button=text=>all.find(x=>x.type==="Btn"&&x.props.text===text);
assert.ok(all.some(x=>x.children.includes("Todavía no has descargado la biblioteca.")));
assert.ok(all.some(x=>x.children.includes("2")));
assert.equal(all.find(x=>x.type==="Switch").props.value,true);
all.find(x=>x.type==="Switch").props.onValueChange(false);
button("Actualizar cancionero").props.onPress();
button("Respaldo y restauración").props.onPress();
button("Acerca de SHALOM ↗").props.onPress();
button("Donaciones ↗").props.onPress();
assert.deepEqual(events,[["wifi",false],["sync"],["tab","Respaldo"],["web","https://shalomcoroacordes-a11y.github.io/Shalom/acerca.html"],["web","https://shalomcoroacordes-a11y.github.io/Shalom/donaciones.html"]]);
const busy=flatten(Screen({...props,busy:true,progress:"Descargando",error:"Error de prueba",copy:{syncedAt:"2026-01-01T12:00:00Z"}}));
assert.equal(busy.find(x=>x.type==="Btn"&&x.props.text==="Actualizando…").props.disabled,true);
assert.ok(busy.some(x=>x.type==="ActivityIndicator"));
for(const value of ["Descargando","Error de prueba"])assert.ok(busy.some(x=>x.children.includes(value)));
assert.ok(busy.some(x=>x.children.some(y=>typeof y==="string"&&y.startsWith("Última actualización: "))));
console.log("SHALOM: settings screen controls, status and navigation verified.");
