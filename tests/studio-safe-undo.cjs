"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),C=require("../studio-core"),codec=require("../studio-codec");
const rows=[{kind:"section",text:"Verso"},{kind:"chords",chordLine:"C G"},{kind:"section",text:"Coro"},{kind:"chords",chordLine:"Am F"}];
const anchors=C.anchorsFromRows(rows),groups=C.groupAnchors(anchors,rows);
const fp=cfg=>JSON.stringify(codec.encode(anchors,cfg));
const original=C.draft(anchors,"4/4",80,2);
const timing=C.undoSnapshot(original);
const moved=C.setDuration(original,0,6);
timing.after=fp(moved);
assert.equal(C.canUndo(timing,fp(moved)),true);
assert.deepEqual(timing.config,original);
const hit=Array.from({length:8},()=>({hit:"up",accent:true}));
const changed=C.applySectionPattern(moved,groups,groups[1],1,hit,"one");
assert.notEqual(fp(changed),fp(moved));
assert.equal(C.canUndo(timing,fp(changed)),false,"Timing undo cannot erase subsequent rhythm edits");
const rhythm=C.undoSnapshot(moved,{section:1,bar:1,hit:0});rhythm.after=fp(changed);
assert.equal(C.canUndo(rhythm,fp(changed)),true);
assert.equal(C.canUndo(rhythm,fp(C.setAnchorHold(changed,2,"ring"))),false);
assert.equal(C.canUndo(timing,fp(rhythm.config)),true,"Restoring rhythm permits the prior timing undo again");
assert.equal(C.canUndo(rhythm,null),false);assert.equal(C.canUndo(null,fp(changed)),false);
assert.equal(C.canUndo(C.undoSnapshot(original),null),false);
const mutable=C.undoSnapshot(original);mutable.config.changes[0].step=999;
assert.notEqual(original.changes[0].step,999);
const src=fs.readFileSync("studio-lab.js","utf8");
assert.match(src,/if\(core.canUndo\(timingUndo,fingerprint\(\)\)\)\{stop\(\);config=timingUndo.config/);
assert.match(src,/if\(!core.canUndo\(rhythmUndo,fingerprint\(\)\)\)return/);
assert.match(src,/timingUndo=null;rhythmUndo=null;renderEditor\(\)/);
assert.match(src,/function showFragment\(fp=fingerprint\(\)\)\{\s*renderEditingState\(fp\)/);
assert.match(src,/previous.after=fingerprint\(\);rhythmUndo=previous/);
assert.equal((src.match(/rememberTiming\(next\);/g)||[]).length,3);
console.log("Studio undo: valid restoration, stale revision rejection, independent snapshot, reset and later edits preserved.");
