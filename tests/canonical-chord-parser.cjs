"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),web=require("../song-chords"),native=require("../native-chords"),{generate}=require("../scripts/build-native-chords");
const read=name=>fs.readFileSync(name,"utf8");
const browser={window:{}};vm.runInNewContext(read("song-chords.js"),browser);
const input="[Coro]\r\nDb  G/B\r\nTexto & <amor>\r\n\r\n(C)Hola (Am)Señor\nF";
const expected='<span class="song-section-label">Coro</span><span class="song-line song-stacked-chords"><span class="chord-line">Db  G/B</span><span class="lyric-line">Texto &amp; &lt;amor&gt;</span></span><span class="song-empty-line"></span><span class="song-line song-inline-chords"><span class="chord-line">C    Am</span><span class="lyric-line">Hola Señor</span></span><span class="song-standalone-chords">F</span>';
assert.equal(web.render(input),expected);
assert.equal(browser.window.ShalomChords.render(input),expected);
assert.equal(native.parseSong(input)[1].chordLine,"C#  G/B");
assert.deepEqual(native.parseSong("(C)Hola (Am)Señor"),[{kind:"chords",chordLine:"C    Am",lyricLine:"Hola Señor"}]);
assert.equal(web.parseRows("C G\n(D)Letra")[0].layout,"stacked");
assert.equal(web.parseRows("(C)Letra")[0].layout,"inline");
assert.match(read("native-chords.js"),/const shared=require\("\.\/song-chords\.js"\)/);
assert.doesNotMatch(read("native-chords.js"),/function (?:inline|merge|chordRow|transposeRow)\(/);
const generated=generate(read);
assert.equal(generated,read("mobile/src/chords.js"));assert.equal(generated,read("admin-mobile/src/chords.js"));
assert.doesNotMatch(generated,/require\("\.\/song-chords\.js"\)/);
const changed=generate(name=>name==="song-chords.js"?read(name).replace("function createChordParser() {","function createChordParser() {\n  // canonical source change"):read(name));
assert.notEqual(changed,generated);
console.log("Canonical chord parser: exact web markup, identity vs native enharmonic behavior, standalone generated native copies and drift verified.");
