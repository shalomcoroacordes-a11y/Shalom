const assert = require("node:assert/strict");
const fs = require("node:fs");
const read = name => fs.readFileSync(name,"utf8");
const join = names => names.map((name,i)=>(i?"\n\n/* ===== "+name+" (original order) ===== */\n":"")+read(name)).join("");
const common = read("public-content-base-bundle.css");
assert.equal(common,join(["site-shell.css","public-cards.css","public-accessibility.css"]));
assert.ok(common.startsWith('@import url("mobile-experience.css?v=1");'));
assert.equal((common.match(/@import/g)||[]).length,1);
const names = ["detalles.css","detail-visuals.css","song-feedback.css","song-reading-mode.css","song-preferences.css","song-reading-mobile-sheet.css","song-capo-mobile-grid.css","song-chords.css","song-print.css","song-reader-cues.css"];
const reader=read("song-reader-bundle.css");
assert.equal(reader,join(names),"Preserve all reader rules byte-for-byte");
assert.doesNotMatch(reader,/@import/);
const styles=[...read("cancion.html").matchAll(/<link rel="stylesheet" href="([^"]+)"/g)].map(m=>m[1]);
assert.deepEqual(styles,["style.css?v=5","public-content-base-bundle.css?v=1","song-reader-bundle.css?v=3","section-reader-web.css?v=2","assets/fonts/inter.css","score-reader.css"]);
assert.equal(fs.existsSync("song-detail-bundle.css"),false);
assert.doesNotMatch(read("offline-sw.js"),/song-detail-bundle\.css/);
console.log("Song reader: exact base and reader CSS, original cascade and print order.");
