"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const window={};
vm.runInNewContext(fs.readFileSync("admin-song-draft.js","utf8"),{window});
const api=window.ShalomAdminSongDraft;
const plain=x=>JSON.parse(JSON.stringify(x));
const empty=api.fromSong(null);
assert.deepEqual(plain(empty.songEdit),{id:null,expected:null});
assert.equal(empty.draft.song_type,"catolico");assert.equal(empty.draft.lyrics,"");assert.equal(empty.draft.new_link_platform,"YouTube");
assert.equal(empty.links.length,0);assert.equal(empty.capos.length,0);
const song={id:"s",updated_at:"rev",title:"Canto",lyrics:"[Coro]\nC   G\nLetra",song_type:"cristiano",tone:"G",capo_position:2,capo_key:"F",_artistLinks:[{artist_id:"a2",role:"colaborador",sort_order:0},{artist_id:"a1",role:"Príncipal",sort_order:3},{artist_id:"a3",sort_order:2}],_categories:[{id:"c1"},{id:"c2"},{id:"c1"},{id:""}],_albums:[{id:"al"}],_links:[{title:"Video",url:"https://example.test",sort_order:8}],_capos:[{label:"Otra",capo_position:"3",capo_key:"E",sort_order:10}]};
const before=JSON.stringify(song);
const value=api.fromSong(song);
assert.deepEqual(plain(value.songEdit),{id:"s",expected:"rev"});
assert.equal(value.draft.main_artist_id,"a1");assert.deepEqual(Array.from(value.draft.collaborators),["a2","a3"]);
assert.deepEqual(Array.from(value.draft.category_ids),["c1","c2"]);assert.equal(value.draft.album_id,"al");assert.equal(value.draft.capo_position,"2");assert.equal(value.draft.lyrics,song.lyrics);
assert.deepEqual(plain(value.links),[{title:"Video",link_type:"Tutorial",platform:"",url:"https://example.test",sort_order:0}]);
assert.deepEqual(plain(value.capos),[{label:"Otra",capo_position:3,capo_key:"E",sort_order:0}]);
assert.equal(JSON.stringify(song),before);
const capture=api.capture(value.draft,{title:"Nuevo",category_id:"different",lyrics:"Nueva letra"},["a3"]);
assert.equal(capture.title,"Nuevo");assert.equal(capture.lyrics,"Nueva letra");assert.deepEqual(Array.from(capture.category_ids),["c1","c2"]);assert.deepEqual(Array.from(capture.collaborators),["a3"]);assert.equal(value.draft.title,"Canto");
assert.deepEqual(Array.from(api.capture({category_id:"legacy"},{},[]).category_ids),["legacy"]);
assert.equal(api.fromSong({_artistLinks:[{artist_id:"late",sort_order:3},{artist_id:"first",sort_order:1}]}).draft.main_artist_id,"first");
const source=fs.readFileSync("admin-pro.js","utf8"),html=fs.readFileSync("admin.html","utf8");
assert.ok(html.indexOf('src="admin-song-draft.js?v=1"')>=0&&html.indexOf('src="admin-song-draft.js?v=1"')<html.indexOf('src="admin-pro.js'));
assert.match(source,/window\.ShalomAdminSongDraft\.fromSong\(song\)/);
assert.match(source,/window\.ShalomAdminSongDraft\.capture\(AP.draft, data, collaborators\)/);
assert.match(source,/if \(!song\) apEditorPosition.clear\("__new__"\)/);
assert.doesNotMatch(source,/const principal = artistLinks.find/);
console.log("Admin draft: empty and existing song, revision, artist order, relations, source integrity, and form merge verified.");
