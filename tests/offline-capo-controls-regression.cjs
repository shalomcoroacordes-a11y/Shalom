"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs");
const {optionsForSong,offset}=require("../offline-capo.js");
const original={tone:"B",capo_position:0,_capos:[]};
assert.deepEqual(optionsForSong(original),[],"Sin versiones: ocultar selector");
const maria={tone:"B",_capos:[{id:"capo2",label:"Capo 2",capo_position:2,capo_key:"A"}]};
const options=optionsForSong(maria);
assert.equal(options.length,2);
assert.equal(options[0].label,"Sin capo");
assert.equal(options[0].offset,0);
assert.equal(options[1].label,"Capo 2 · Figuras en A");
assert.equal(options[1].offset,-2,"B con capo 2 usa figuras en A");
assert.equal(offset({tone:"E"},2,"D"),-2);
assert.equal(offset({tone:"Bb"},2,"G#"),-2,"Aceptar notas en bemol");
assert.equal(offset({tone:""},3,""),-3,"Usar posición como alternativa");
const main=optionsForSong({tone:"G",capo_position:3,capo_key:"E",_capos:[]});
assert.equal(main.length,2,"Capo del canto principal también seleccionable");
assert.equal(main[1].offset,-3);
assert.equal(optionsForSong({tone:"G",_capos:[{capo_position:0,capo_key:"E"}]}).length,0,"No mostrar capo vacío");
assert.equal(optionsForSong({tone:"G",_capos:[{capo_position:16,capo_key:"E"}]}).length,0,"Rechazar posiciones inválidas");
assert.equal(optionsForSong({tone:"B",_capos:[{capo_position:2,capo_key:"A"},{capo_position:2,capo_key:"A"}]}).length,2,"No duplicar versión");
const html=fs.readFileSync("offline.html","utf8");
const js=fs.readFileSync("offline.js","utf8");
const sw=fs.readFileSync("offline-sw.js","utf8");
assert.match(html,/id="capoPanel" hidden/);
assert.match(html,/id="capoChoices"/);
assert.ok(html.indexOf("offline-capo.js")<html.indexOf("offline.js"));
assert.match(js,/renderCapoControls\(song\)/);
assert.match(js,/state\.shift \+ capo\.offset/);
assert.match(js,/aria-pressed/);
assert.match(js,/state\.capoChoice = "original"/);
const version=sw.match(/const VERSION = "shalom-offline-shell-v(\d+)[^"]*"/);
assert.ok(version&&Number(version[1])>=2,"La caché de Offline debe conservar una versión compatible con capo");
assert.match(sw,/"\.\/offline-capo\.js"/);
console.log("Capos Offline: selección, transposición y precarga sin conexión verificadas.");
