"use strict";
// Assets generated at build time, not a network request from the app.
// The same source, font bytes and CSS are used by both offline WebViews.
const fs=require("node:fs/promises"),path=require("node:path");
const {prepare,assets,verify}=require("./prepare-inter-font");
const root=path.resolve(__dirname,"..");
const read=name=>fs.readFile(path.join(root,name),"utf8");
async function run(){
 await prepare();
 const font=await fs.readFile(path.join(root,assets[0].target));verify(font,assets[0]);
 const [css,layout,reader,license,html,zoom,palette]=await Promise.all([
  read("score-reader.css"),read("score-layout.js"),read("score-reader.js"),read(assets[1].target),
  read("mobile/src/web-score-html.js"),read("mobile/src/score-zoom.js"),read("mobile/src/palette.js")
 ]);
 const bundle="// Generated by scripts/build-native-score.js. Do not edit.\nmodule.exports="+JSON.stringify({font:font.toString("base64"),css,layout,reader,license})+";\n";
 for(const dir of ["mobile","admin-mobile"]){
  const folder=path.join(root,dir,"src");
  await fs.writeFile(path.join(folder,"score-reader-assets.js"),bundle);
  if(dir==="admin-mobile")for(const [name,content] of Object.entries({"web-score-html.js":html,"score-zoom.js":zoom,"palette.js":palette})){
   await fs.writeFile(path.join(folder,name),"// Generated from mobile/src/"+name+". Run node scripts/build-native-score.js.\n"+content);
  }
  await fs.mkdir(path.join(root,dir,"assets","fonts"),{recursive:true});
  await fs.writeFile(path.join(root,dir,"assets","fonts","Inter-OFL.txt"),license);
 }
 console.log("Native Inter documents bundled for public and admin; no runtime network required.");
}
run().catch(e=>{console.error(e.message);process.exitCode=1;});
